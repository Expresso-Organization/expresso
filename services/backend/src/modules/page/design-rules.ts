/**
 * 포트폴리오를 디자인하는 호출이 지키는 Do와 Do not.
 *
 * 2026-11-19에 사용자가 확정한 목록의 「디자인」 · 「사실」 절이다. 이 제품이 파는 것은 포트폴리오를 **디자인**해 주는 일이고,
 * 사실을 문단과 표로 나열한 결과는 디자인이 아니다 — 그날 대화가 그린 「문서형 · 작업물 목록형」 첫 화면을 두고
 * 사용자가 "이건 포트폴리오가 아니라 문서"라고 짚었다.
 *
 * 첫 화면을 그리는 호출(`design-chat/prompts.ts`)과, 고른 첫 화면 뒤를 잇는 지면 호출(`briefed-generator.ts`의 `seedPrompt`)이
 * 같은 목록을 읽는다. 첫 화면만 디자인되고 그 뒤가 문서로 돌아가면 고른 것과 만든 것이 어긋난다.
 *
 * 2026-11-20 사용자: "이런 수치에 집착하는 경향을 좀 줄여봐. 모든 포트폴리오가 다 이걸로 시작해" — 첫 화면마다 「전후 수치 대비」
 * 막대가 주인공으로 섰다. 그릴 것의 첫머리에 전후 비교 · 차트를 두고 첫 화면의 사실을 숫자로 뽑게 한 탓이다. 주인공은 이 사람이
 * 만든 것에서 고르고, 수치는 그 곁의 근거로 둔다.
 *
 * 같은 날 사용자: "첫 화면의 시각적 요소는 이렇게 svg로 그림을 그리기보다, 이 사람의 커리어 기록과 스타일, 강조할 점을 중심으로
 * 추상적인 디자인 요소를 만드는 게 더 낫다… svg/canvas로 그림을 그리거나, three.js를 활용하는 방향으로." — 화면 · 구조도를
 * 따라 그린 설명도가 모든 첫 화면을 같게 만들었다. 그림은 기록에서 계산한 값으로 형태를 짓는 추상 그래픽으로 잡는다.
 *
 * 그 뒤 견본 다섯 장 중 넷이 경력 기간을 막대 · 차선 · 시간 축으로 옮긴 타임라인 차트였고, 수치 카드(「1.9초」)가 다시 크게 섰다.
 * 사용자가 고른 방향은 점의 흐름처럼 바라보는 형태다 — 값은 형태 · 흐름 · 밀도로 옮기고, 수치는 첫 화면에 한 줄로만 둔다.
 *
 * 다음 견본에서 기본 상자를 Lambert 재질로 늘어놓은 three.js 무대가 나왔다. 사용자: "이런 저퀄리티 박스는 쓰지 않게 해야겠다".
 * 형태 · 재질 · 빛의 짝은 3d-motion-web 스킬의 FORM × MATERIAL 규칙에서 가져와 `PAGE_SCRIPT_PROMPT`에 둔다.
 */
export function designRules(scope: "화면" | "섹션"): string[] {
  return [
    "## Do",
    "- 포트폴리오를 디자인한다. 구성, 시각 위계, 타이포그래피로 이 사람이 무슨 일을 하는 사람인지 한눈에 알아보게 한다.",
    ...(scope === "화면"
      ? [
          "- 첫 화면의 그림은 이 사람의 커리어 기록 · 고른 스타일 · 강조할 점에서 나온 추상적인 그래픽이다. 화면이나 구조도를 따라 그린 설명도 대신, 이 사람의 일이 어떤 성격인지 형태로 느껴지게 한다.",
          "- 기록의 값은 형태 · 흐름 · 밀도 · 결로 옮긴다. 기간은 흐름의 길이나 겹, 일의 갈래는 색이나 결, 강조할 점은 가장 밝거나 빽빽하거나 빠른 자리가 된다. 읽어 내는 차트가 아니라 바라보는 형태다 — 시간 축 · 막대 · 차선 · 눈금 · 연도 이름표 없이 짓는다.",
          "- 그래픽은 그림 스크립트로 짓는다 — canvas 2D로 그린 생성 그래픽이나 three.js 장면. 값(점 · 선 · 면의 수, 간격, 속도, 색의 비율)은 위 기록에서 계산해 스크립트에 적는다. SVG는 그 아래 깔리는 첫 모습에 쓴다.",
          "- 깊이가 있는 장면(고른 레이아웃이 3D 장면이거나, 형태가 공간에 놓이는 그림)은 three.js로 짓는다. 원근 · 회전 · 조명을 canvas 2D에서 손으로 계산하지 않는다.",
          "- 3D 장면은 공들인 오브젝트 하나 또는 하나로 이어진 장이다 — 재질과 빛까지 디자인해, 크롬 · 유리 · 세라믹 · 빛나는 입자처럼 무엇으로 만들었는지가 보이게 한다. 기본 도형을 늘어놓은 데모처럼 보이면 다시 짓는다.",
        ]
      : ["- 섹션의 그림은 첫 화면의 그래픽이 쓴 형태 · 색 · 움직임을 이어, 그 섹션의 일을 받친다."]),
    "- 그래픽의 색은 고른 스타일의 것이다. 이름과 한 줄 소개는 그래픽과 겹치거나 맞물리게 놓아 한 장면으로 읽히게 한다.",
    ...(scope === "화면"
      ? ["- 수치는 첫 화면에 한 줄 글로만 둔다(한두 개, 본문 글자 크기). 크게 세울 자리는 그래픽과 이름이 차지한다 — 수치 카드 · 큰 숫자 · 수치 띠는 첫 화면 뒤 섹션의 몫이다."]
      : ["- 수치는 그 일을 받치는 근거로 그 일 곁에 둔다. 수치를 크게 세우거나 전후를 막대로 견주는 것은 그 섹션이 수치를 주인공으로 정했을 때만이다."]),
    `- ${scope}마다 주인공을 하나 세우고 나머지는 그것을 받치게 한다. 크기, 자리, 대비의 차이를 크게 둔다.`,
    "- 구도는 이 사람의 자료와 고른 레이아웃에서 정한다. 다른 사람의 포트폴리오에 그대로 옮겨도 되는 구도라면 다시 잡는다.",
    "- 자료의 사실은 재료다. 무엇을 크게, 무엇을 작게, 무엇을 뒤로 미룰지 정한다.",
    "- 이름, 수치, 기간은 자료에 적힌 그대로 쓴다.",
    "",
    "## Do not",
    "- 사실을 문단과 표로 나열하지 않는다. 문서나 이력서처럼 보이면 실패다.",
    "- 「이름 + 한 줄 소개 + 큰 수치 하나」 구도를 기본값으로 쓰지 않는다. 고른 레이아웃이 그렇게 정했을 때만 쓴다.",
    "- 같은 모양의 카드를 줄지어 쌓지 않는다.",
    "- 내용 없는 꾸밈을 넣지 않는다 — 뜻 없는 그러데이션, 장식 도형, 장식 아이콘.",
    "- 자료에 없는 수치, 경력, 연락처를 만들지 않는다. 그림을 채우려고 수치를 지어내지 않는다.",
    "",
  ];
}
