/**
 * 포트폴리오를 디자인하는 호출이 지키는 Do와 Do not.
 *
 * 2026-11-19에 사용자가 확정한 목록의 「디자인」 · 「사실」 절이다. 이 제품이 파는 것은 포트폴리오를 **디자인**해 주는 일이고,
 * 사실을 문단과 표로 나열한 결과는 디자인이 아니다 — 그날 대화가 그린 「문서형 · 작업물 목록형」 첫 화면을 두고
 * 사용자가 "이건 포트폴리오가 아니라 문서"라고 짚었다.
 *
 * 첫 화면을 그리는 호출(`design-chat/prompts.ts`)과, 고른 첫 화면 뒤를 잇는 지면 호출(`briefed-generator.ts`의 `seedPrompt`)이
 * 같은 목록을 읽는다. 첫 화면만 디자인되고 그 뒤가 문서로 돌아가면 고른 것과 만든 것이 어긋난다.
 *
 * 2026-11-20 사용자: "이런 수치에 집착하는 경향을 좀 줄여봐. 모든 포트폴리오가 다 이걸로 시작해" — 첫 화면마다 「전후 수치 대비」
 * 막대가 주인공으로 섰다. 그릴 것의 첫머리에 전후 비교 · 차트를 두고 첫 화면의 사실을 숫자로 뽑게 한 탓이다. 주인공은 이 사람이
 * 만든 것에서 고르고, 수치는 그 곁의 근거로 둔다.
 *
 * 같은 날 사용자: "첫 화면의 시각적 요소는 이렇게 svg로 그림을 그리기보다, 이 사람의 커리어 기록과 스타일, 강조할 점을 중심으로
 * 추상적인 디자인 요소를 만드는 게 더 낫다… svg/canvas로 그림을 그리거나, three.js를 활용하는 방향으로." — 화면 · 구조도를
 * 따라 그린 설명도가 모든 첫 화면을 같게 만들었다. 그림은 기록에서 계산한 값으로 형태를 짓는 추상 그래픽으로 잡는다.
 *
 * 그 뒤 견본 다섯 장 중 넷이 경력 기간을 막대 · 차선 · 시간 축으로 옮긴 타임라인 차트였고, 수치 카드(「1.9초」)가 다시 크게 섰다.
 * 사용자가 고른 방향은 점의 흐름처럼 바라보는 형태다 — 값은 형태 · 흐름 · 밀도로 옮긴다.
 *
 * 「수치는 한 줄」로 둔 뒤에도 모든 첫 화면의 소개 문장 끝에 「상품 상세 LCP 3.8초 → 1.9초」가 붙었다. 사용자: "수치에 왜 계속
 * 집착하는거냐 대체"(같은 날, 세 번째). 첫 화면에는 수치를 두지 않는다. 수치는 그 일을 풀어 쓰는 섹션의 몫이다.
 *
 * 다음 견본에서 기본 상자를 Lambert 재질로 늘어놓은 three.js 무대가 나왔다. 사용자: "이런 저퀄리티 박스는 쓰지 않게 해야겠다".
 * 형태 · 재질 · 빛의 짝은 3d-motion-web 스킬의 FORM × MATERIAL 규칙에서 가져와 `PAGE_SCRIPT_PROMPT`에 둔다.
 * 사용자가 그 스킬의 엔진을 지면에 싣기로 했다("Build in the engine") — 아래 결정으로 걷어냈다.
 *
 * 2026-11-21 사용자: "3D 오브젝트 하나 둥둥 떠있는 방식은 솔직히 예쁘지도 않고 그냥 이상한데" · 입자 · 프리즘 시안도 어색했다.
 * "웹용 3D 인터랙티브 오브젝트랑 파티클 효과는 인터넷에 찾아보면 많을 거야. 그걸 라이브러리로 흡수하도록 하고, 모델이 라이브러리를
 * 참고하도록 하자" — 3D · 입자는 효과 라이브러리(packages/contracts/effects)에서 고른다.
 *
 * 라이브러리의 실제 견본(액체 방울 · 지구본)을 본 사용자: "이미지로 보는데 너무 끔찍하네. 의미없는 3D 오브젝트는 그냥 안쓰는게 더 낫겠다"
 * (같은 날). 3D는 배경 장과 블루프린트 선화로만 쓴다. 방울 · 지구본 효과와 MotionWeb 엔진을 걷어냈다.
 *
 * 그 지침으로 같은 사람을 세 짝(스타일 × 레이아웃)으로 그리자 2D 세 장이 모두 「흩어진 선이 한 다발로 모인다」였다. 형태를 기록에서만
 * 고르게 했고(「기간은 흐름의 길이나 겹, 강조할 점은 가장 밝거나 빽빽한 자리」) 기록은 짝마다 같으니 답도 같았다. 형태의 계열은
 * 짝마다 달라지는 스타일 · 그림 자리에서 고르고, 기록은 그 형태의 값만 정한다(사용자 "고쳐 줘").
 * 그 뒤 계열 이름(점 · 격자 · 면 · 모듈 …)을 늘어놓자 세 장이 모두 「모듈 격자」가 되었다 — 목록은 모델이 가장 무난한 하나를 고르게 한다.
 * 사용자: "계속 정형화된 똑같은 패턴이 나오는 거 문제가 좀 있어. 기본은 커리어 기록과 지원 대상, 포트폴리오 내용에 맞춰서 추상화된
 * 디자인 요소를 canvas로 그리도록 하고, 3D 디자인 등은 사용자가 카탈로그에서 선택할 수 있는 요소로 하자"(같은 날). 목록을 걷고,
 * 모티프를 그 사람의 일에서 가져오게 한다. 효과는 사용자가 고른 것만 싣는다.
 */
export function designRules(scope: "화면" | "섹션"): string[] {
  return [
    "## Do",
    "- 포트폴리오를 디자인한다. 구성, 시각 위계, 타이포그래피로 이 사람이 무슨 일을 하는 사람인지 한눈에 알아보게 한다.",
    ...(scope === "화면"
      ? [
          "- 첫 화면의 그림은 이 사람만의 추상 그래픽이다. 재료는 셋이다 — 커리어 기록(근거), 지원하는 공고와 직무(설계안), 포트폴리오에 담을 내용(섹션 설계). 화면이나 구조도를 따라 그린 설명도 대신, 이 사람의 일이 어떤 성격인지 형태로 느껴지게 한다.",
          "- 모티프는 이 사람의 일에서 가져온다. 공고가 찾는 것과 기록에서 가장 크게 다룰 일을 맞대 보고, 그 일에만 있는 구조 · 움직임 · 리듬(만든 것의 생김새, 다룬 것의 모양, 일한 방식)을 추상화한다. 다른 사람의 포트폴리오에 그대로 옮겨도 맞는 형태라면 모티프를 다시 잡는다. 정한 모티프는 `note`에 한 문장으로 적는다.",
          "- 고른 스타일과 그림 자리가 그 모티프를 어떻게 그릴지 정한다 — 선의 굵기와 끝, 면의 채움, 밀도, 움직임의 빠르기, 자리에 맞는 배치.",
          "- 기록은 그 형태의 값을 정한다 — 개수 · 크기 · 간격 · 겹 · 색의 배분. 강조할 점은 대비가 가장 큰 자리가 된다. 읽어 내는 차트가 아니라 바라보는 형태다 — 시간 축 · 막대 · 차선 · 눈금 · 연도 이름표 없이 짓는다.",
          "- 그래픽은 canvas 2D 그림 스크립트로 직접 짓는다. SVG는 그 아래 깔리는 첫 모습에 쓴다. 원근 · 회전 · 조명을 손으로 계산하지 않는다.",
          "- 효과(3D · 입자 · 안개 · 선화)는 사용자가 카탈로그에서 골랐을 때만 쓴다 — 그때는 「사용자가 고른 그래픽」이 그 효과 하나를 알려 준다. 고르지 않았으면 효과를 부르지 않는다. 3D 오브젝트(도형 · 덩어리 · 구 · 결정)는 짓지도 띄우지도 않는다.",
        ]
      : ["- 섹션의 그림은 첫 화면의 그래픽이 쓴 형태 · 색 · 움직임을 이어, 그 섹션의 일을 받친다."]),
    "- 그래픽의 색은 고른 스타일의 것이다. 이름과 한 줄 소개는 그래픽과 겹치거나 맞물리게 놓아 한 장면으로 읽히게 한다.",
    ...(scope === "화면"
      ? ["- 첫 화면에는 수치를 두지 않는다 — 성과 수치(시간 · 용량 · 비율 · 건수, 전후 비교)를 소개 문장 · 곁의 글 · 카드 어디에도 쓰지 않는다. 재직 기간 같은 날짜는 수치가 아니다. 첫 화면은 이 사람이 누구이고 어떤 일을 하는지를 이름 · 한 줄 소개 · 그래픽으로 보인다. 수치는 그 일을 풀어 쓰는 뒤 섹션에 둔다."]
      : ["- 수치는 그 일을 받치는 근거로 그 일 곁에 둔다. 수치를 크게 세우거나 전후를 막대로 견주는 것은 그 섹션이 수치를 주인공으로 정했을 때만이다."]),
    `- ${scope}마다 주인공을 하나 세우고 나머지는 그것을 받치게 한다. 크기, 자리, 대비의 차이를 크게 둔다.`,
    "- 구도는 이 사람의 자료와 고른 레이아웃에서 정한다. 다른 사람의 포트폴리오에 그대로 옮겨도 되는 구도라면 다시 잡는다.",
    "- 자료의 사실은 재료다. 무엇을 크게, 무엇을 작게, 무엇을 뒤로 미룰지 정한다.",
    "- 이름, 수치, 기간은 자료에 적힌 그대로 쓴다.",
    "",
    "## Do not",
    "- 사실을 문단과 표로 나열하지 않는다. 문서나 이력서처럼 보이면 실패다.",
    "- 「이름 + 한 줄 소개 + 큰 수치 하나」 구도를 기본값으로 쓰지 않는다. 고른 레이아웃이 그렇게 정했을 때만 쓴다.",
    "- 같은 모양의 카드를 줄지어 쌓지 않는다.",
    "- 내용 없는 꾸밈을 넣지 않는다 — 뜻 없는 그러데이션, 장식 도형, 장식 아이콘.",
    "- 자료에 없는 수치, 경력, 연락처를 만들지 않는다. 그림을 채우려고 수치를 지어내지 않는다.",
    "",
  ];
}
