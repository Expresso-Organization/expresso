/**
 * 공고 본문의 강조 자국을 편다.
 *
 * 공고 원문은 회사의 채용 시스템이 HTML로 갖고 있던 것을 마크다운으로 옮긴
 * 결과다. 그 변환기가 `<b>` 태그를 옮기면서 남긴 자국이 있는데, 마크다운
 * 규칙으로는 강조가 되지 못하고 **별표가 글자 그대로 화면에 선다.**
 *
 * 쿠팡 공고 25건이 `**전형****절차**`를 이렇게 갖고 있고, 화면에는
 * `전형****절차`라고 뜬다. 우리 버그가 아니라 CommonMark가 그렇게 정한 것이다 —
 * 여닫이 양쪽이 될 수 있는 별표 뭉치는 앞뒤 길이의 합이 3의 배수면 짝을 짓지
 * 못한다(`**A` + `****` = 2+4 = 6). `**abc****def**`도 똑같이 깨진다.
 *
 * 고치는 곳이 여기인 이유는 **`description_raw`를 고칠 수 없기 때문**이다.
 * 원문은 못 바꾸게 막아 뒀고(0002 트리거), 그게 맞다 — 출처가 뭐라고 적었는지는
 * 남아야 한다. 그래서 저장된 글자는 그대로 두고 **그리는 순간에만** 편다.
 *
 * ## 손대지 않는 것
 *
 * 별표가 남는다고 다 자국은 아니다. `\*해당 절차는 변동될 수 있습니다` 처럼
 * **출처가 일부러 이스케이프한 별표**는 각주 표시다. 크래프톤 6건 · 쿠팡 4건이
 * 이렇게 쓰는데, 이건 지금 그대로 나오는 게 맞다. 아래 규칙은 이스케이프된
 * 별표(`\*`)를 건드리지 않는다.
 */

/**
 * ① 붙어 있는 강조 두 개의 이음매.
 *
 * `**전형****절차**` — 변환기가 `<b>전형</b><b>절차</b>`를 그대로 옮긴 것이다.
 * 가운데 네 개를 걷어내면 `**전형절차**`가 되어 글자도 굵기도 그대로 산다.
 *
 * 양옆이 공백이 아닐 때만 본다. 줄 어딘가에 홀로 선 `****`는 이음매가 아니다.
 */
const SEAM = /(?<=\S)\*{4}(?=\S)/g;

/**
 * ② 닫는 별표만 다음 줄로 밀려난 경우.
 *
 * ```            ```
 * **Remuneration  **\[AI Research 본부 비전\]
 * **             **크래프톤 AI Research 본부는 …
 * ```            ```
 *
 * 줄바꿈 뒤의 `**`는 앞이 공백이라 닫지 못한다. 앞 줄 끝의 공백까지 함께
 * 걷어야 `**Remuneration**`이 된다 — `**Remuneration  **`은 여전히 안 닫힌다.
 *
 * 오른쪽처럼 밀려난 별표 뒤에 글이 이어 붙기도 해서 정규식으로는 안 된다.
 * 필요한 판단이 **앞 줄에 짝 없는 여는 별표가 있는가**인데, 그건 세어 봐야
 * 안다. 이 조건이 없으면 `**강조**` 다음 줄이 `**강조**`로 시작하는 멀쩡한
 * 글에서 두 줄이 붙어 버린다.
 */
function pullClosersBack(markdown: string): string {
  const lines = markdown.split("\n");
  for (let index = 1; index < lines.length; index += 1) {
    const line = lines[index] ?? "";
    const above = lines[index - 1] ?? "";
    if (!line.startsWith("**") || !hasOpenEmphasis(above)) continue;
    lines[index - 1] = `${above.replace(/[ \t]+$/, "")}**`;
    const rest = line.slice(2);
    // 별표만 있던 줄은 빈 줄로 남긴다. 공백만 남기면 줄바꿈 표시로 읽힌다.
    lines[index] = rest.trim() === "" ? "" : rest;
  }
  return lines.join("\n");
}

/**
 * 이 줄에 짝을 못 찾은 여는 별표가 있는가.
 *
 * 별표 뭉치를 세어 홀수면 하나가 열린 채 끝났다는 뜻이다. 출처가 이스케이프한
 * 별표(`\*`)는 글자지 표시가 아니므로 세기 전에 걷어낸다 — 각주 표시가 붙은
 * 줄이 열려 있다고 잘못 읽히면 안 된다.
 */
function hasOpenEmphasis(line: string): boolean {
  const runs = line.replace(/\\./g, "").match(/\*{2,}/g);
  return runs !== null && runs.length % 2 === 1;
}

/**
 * ③ 여는 별표만 앞 줄에 남은 경우.
 *
 * ```
 * **
 * 자격 요건**
 * ```
 *
 * `### **` 처럼 앞에 블록 표시가 붙어 오기도 한다(크래프톤 1건). 그래서 줄
 * 앞부분(`$1`)은 살려 두고 줄바꿈만 걷는다.
 *
 * **다음 줄이 닫는 별표를 들고 있을 때만** 당긴다. 이 조건이 없으면
 * `-   **자격 요건**` 다음에 `-   **경력**`이 오는 멀쩡한 목록에서 두 줄이
 * 붙어 버린다. 앞부분에 별표가 없어야 한다는 조건(`[^*\n]*`)도 같은 이유다.
 */
const ORPHAN_OPENER = /^([^*\n]*)\*\*[ \t]*\n(?=[^*\n]*\*\*[ \t]*$)/gm;

export function mendEmphasis(markdown: string): string {
  return pullClosersBack(markdown.replace(SEAM, "")).replace(ORPHAN_OPENER, "$1**");
}
